import {readFile,writeFile,readdir,mkdir,cp,rm,stat} from 'node:fs/promises';
import {resolve,join,relative,dirname} from 'node:path';
import {createHash} from 'node:crypto';
const root=process.cwd(), input=join(root,'dist/client'), output=join(root,'docs');
// Fail before packaging if any presentation slide is missing or truncated.
for(const [folder,total] of [['slides',23],['slides/retail-shopping',20]]){
 for(let slide=1;slide<=total;slide++){
  const path=join(input,folder,`slide-${slide}.webp`),data=await readFile(path);
  if(data.length<20||data.toString('ascii',0,4)!=='RIFF'||data.toString('ascii',8,12)!=='WEBP'||data.readUInt32LE(4)+8!==data.length)throw new Error(`Invalid presentation image: ${folder}/slide-${slide}`);
 }
}
try {await stat(output);await readFile(join(output,'.portfolio-generated'),'utf8');await rm(output,{recursive:true});}catch(e){if(e.code!=='ENOENT')throw e; const exists=await stat(output).catch(()=>null);if(exists)throw new Error('Refusing to overwrite a docs directory not generated by this script.');}
await cp(input,output,{recursive:true});
// Public disclosure of the CV file still needs specific authorization.
await rm(join(output,'files','David-Alter-CV.pdf'),{force:true});
await writeFile(join(output,'.portfolio-generated'),'Generated by scripts/prepare-github-pages.mjs\n');
await writeFile(join(output,'.nojekyll'),'');
async function files(dir){const result=[];for(const entry of await readdir(dir,{withFileTypes:true})){const path=join(dir,entry.name);if(entry.isDirectory())result.push(...await files(path));else result.push(path);}return result;}
let count=0;
for(const file of await files(output)){
 if(file.endsWith('.map')){await rm(file);continue;}
 if(!file.endsWith('.html'))continue;
 let html=await readFile(file,'utf8');
 const hashes=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].filter(m=>!m[1].match(/\bsrc\s*=/i)&&m[2].trim()).map(m=>`'sha256-${createHash('sha256').update(m[2]).digest('base64')}'`);
 const csp=["default-src 'self'",`script-src 'self' ${[...new Set(hashes)].join(' ')}`,"script-src-attr 'none'","style-src 'self' 'unsafe-inline'","img-src 'self' data: blob:","font-src 'self'","connect-src 'self'","frame-src https://drive.google.com","media-src 'self' blob:","object-src 'none'","base-uri 'none'","form-action 'none'"].join('; ');
 html=html.replace('<head>','<head><meta http-equiv="Content-Security-Policy" content="'+csp+'">');
 await writeFile(file,html);count++;
 const route=relative(output,file);
 if(route!=='index.html'&&route!=='404.html'){
  const alias=join(output,route.slice(0,-5),'index.html');await mkdir(dirname(alias),{recursive:true});await writeFile(alias,html);
 }
}
await writeFile(join(output,'robots.txt'),'User-agent: *\nAllow: /\n');
console.log(JSON.stringify({directory:output,securedHTMLPages:count,host:'GitHub Pages, user-site repository root'}));
